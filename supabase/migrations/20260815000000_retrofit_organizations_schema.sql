CREATE TABLE IF NOT EXISTS public.countries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL UNIQUE,
  iso_code VARCHAR,
  phone_code VARCHAR,
  currency VARCHAR,
  currency_code VARCHAR,
  currency_symbol VARCHAR,
  is_active BOOLEAN DEFAULT true,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.organizations (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  organization_type TEXT NOT NULL,
  logo_url TEXT,
  country_id BIGINT REFERENCES public.countries(id),
  city_id BIGINT,
  commune_id BIGINT,
  email TEXT,
  telephone TEXT,
  whatsapp TEXT,
  address TEXT,
  actif BOOLEAN DEFAULT true,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
  created_by UUID REFERENCES auth.users(id),
  commercial_agent_id UUID REFERENCES auth.users(id),
  validation_status TEXT NOT NULL DEFAULT 'pending',
  validated_by UUID REFERENCES auth.users(id),
  validated_at TIMESTAMP WITH TIME ZONE
);

CREATE TABLE IF NOT EXISTS public.organization_roles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id BIGINT NOT NULL REFERENCES public.organizations(id),
  name TEXT NOT NULL,
  code TEXT NOT NULL UNIQUE,
  description TEXT,
  actif BOOLEAN DEFAULT true,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
  hierarchy_level INTEGER NOT NULL DEFAULT 99,
  parent_role_id BIGINT REFERENCES public.organization_roles(id)
);

CREATE TABLE IF NOT EXISTS public.permissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  description TEXT,
  category TEXT,
  actif BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.role_permissions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_role_id BIGINT NOT NULL REFERENCES public.organization_roles(id),
  permission_id BIGINT NOT NULL REFERENCES public.permissions(id),
  actif BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.access_scopes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id UUID NOT NULL REFERENCES auth.users(id),
  organization_id BIGINT NOT NULL REFERENCES public.organizations(id),
  scope_type TEXT NOT NULL,
  scope_id BIGINT,
  actif BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  country_id BIGINT REFERENCES public.countries(id)
);

CREATE TABLE IF NOT EXISTS public.user_management (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  manager_user_id UUID NOT NULL REFERENCES auth.users(id),
  managed_user_id UUID NOT NULL REFERENCES auth.users(id),
  organization_id BIGINT NOT NULL REFERENCES public.organizations(id),
  actif BOOLEAN NOT NULL DEFAULT true,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT now(),
  UNIQUE (manager_user_id),
  UNIQUE (managed_user_id),
  UNIQUE (organization_id)
);

