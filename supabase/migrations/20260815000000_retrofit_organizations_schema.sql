DROP POLICY IF EXISTS admin_read_countries ON public.countries;
CREATE POLICY admin_read_countries ON public.countries FOR SELECT TO authenticated
  USING (EXISTS (SELECT 1 FROM public.user_roles WHERE user_roles.user_id = auth.uid() AND user_roles.role = 'admin'::text));

DROP POLICY IF EXISTS admin_read_organizations ON public.organizations;
CREATE POLICY admin_read_organizations ON public.organizations FOR SELECT TO authenticated
  USING (EXISTS (SELECT 1 FROM public.user_roles WHERE user_roles.user_id = auth.uid() AND user_roles.role = 'admin'::text));

DROP POLICY IF EXISTS admin_read_organization_roles ON public.organization_roles;
CREATE POLICY admin_read_organization_roles ON public.organization_roles FOR SELECT TO authenticated
  USING (EXISTS (SELECT 1 FROM public.user_roles WHERE user_roles.user_id = auth.uid() AND user_roles.role = 'admin'::text));
